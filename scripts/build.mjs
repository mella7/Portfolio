#!/usr/bin/env node
// Builds the site into dist/. No dependencies: Node 20+ only.
//
//   node scripts/build.mjs                 site served from the domain root
//   BASE_PATH=/Portfolio node scripts/build.mjs   site served from a sub-path
//
// Steps: copy public/ -> render every page from src/data -> bundle CSS ->
// copy client scripts -> write sitemap, RSS, robots.txt and security headers.

import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SITE, THEMES, MODES } from "../src/data/site.mjs";
import * as C from "../src/data/content.mjs";
import { escapeHtml } from "../src/lib/html.mjs";
import { parseFrontMatter, renderMarkdown, readingMinutes } from "../src/lib/markdown.mjs";
import { frameVars, frameImage, cssBlock } from "../src/lib/nine-slice.mjs";
import { setBase, u } from "../src/views/parts.mjs";
import { layout, CSP, analyticsUrl } from "../src/views/layout.mjs";
import { homePage, homeJsonLd } from "../src/views/home.mjs";
import * as P from "../src/views/pages.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const DIST = join(ROOT, "dist");
const BASE = (process.env.BASE_PATH ?? "").replace(/\/+$/, "");

setBase(BASE);

const read = (...parts) => readFileSync(join(...parts), "utf8");
function write(path, content) {
  const file = join(DIST, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

// ------------------------------------------------------------------ styles

// Order matters: tokens and base first, page-specific rules last.
const STYLE_FILES = ["base.css", "cards.css", "home.css", "sections.css", "terminal.css", "pages.css", "motion.css"];

function generatedCss() {
  const card = { cornerSize: 40, thickness: 1 };
  const frame = (mode, stroke) => frameImage({ ...card, fill: MODES[mode].card, stroke: stroke ?? MODES[mode].line });
  const out = [
    "/* Generated by scripts/build.mjs: frame images and per-theme values. */",
    cssBlock(":root", {
      ...frameVars("ns", card),
      ...frameVars("bt", { cornerSize: 20, thickness: 1.5 }),
      "--ns-image": frame("dark"),
    }),
    cssBlock('[data-mode="light"]', { "--ns-image": frame("light") }),
  ];
  for (const t of THEMES) {
    out.push(
      cssBlock(`[data-theme="${t.id}"]`, {
        // --a-base / --a-tint never change; --a / --a-soft follow the mode.
        "--a-base": t.accent,
        "--a-tint": t.soft,
        "--on-base": t.on,
        "--a-light": t.light,
        "--sheet": `url("${BASE}/avatar-spin-${t.id}.webp")`,
        "--walk-sheet": `url("${BASE}/avatar-walk-${t.id}.webp")`,
        // Painted frame with an accent outline, for browsers without mask-border.
        "--ns-image-hover": frame("dark", t.accent),
      }),
      cssBlock(`[data-mode="light"][data-theme="${t.id}"]`, { "--ns-image-hover": frame("light", t.light) }),
      `.swatch--${t.id}{background:${t.accent}}`,
    );
  }
  // The photo strip moves at a constant speed: 4 seconds per slide.
  const counts = new Set([C.testimonials.length, C.moments.filter((m) => m.w > m.h).slice(0, 12).length]);
  for (const n of counts) out.push(`.slideshow__track--${n}{animation-duration:${n * 4}s}`);
  return out.join("\n");
}

const css = [generatedCss(), ...STYLE_FILES.map((f) => read(SRC, "styles", f))].join("\n").replaceAll("__BASE__", BASE);

// ------------------------------------------------------------------ assets

const clientFiles = readdirSync(join(SRC, "client")).filter((f) => f.endsWith(".js"));
const hash = createHash("sha256");
hash.update(css);
for (const f of clientFiles) hash.update(read(SRC, "client", f));
hash.update(read(SRC, "data", "world.json"));
const version = hash.digest("hex").slice(0, 10);

// Everything under /assets/<version>/ can be cached forever: a change to any
// stylesheet or script changes the folder name.
const assetDir = `/assets/${version}`;
const assets = {
  css: u(`${assetDir}/site.css`),
  boot: u(`${assetDir}/js/boot.js`),
  js: u(`${assetDir}/js/main.js`),
};

// ------------------------------------------------------------------- globe
// Country outlines for the globe on /travel, cut down to what it needs:
// outer rings only, one decimal place (about 11 km), no repeated points.

const worldData = JSON.stringify(
  JSON.parse(read(SRC, "data", "world.json")).features.map((feature) => {
    const polygons = feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
    const rings = polygons
      .map((polygon) => {
        const flat = [];
        for (const [lon, lat] of polygon[0]) {
          const x = Math.round(lon * 10) / 10;
          const y = Math.round(lat * 10) / 10;
          if (flat.length && flat[flat.length - 2] === x && flat[flat.length - 1] === y) continue;
          flat.push(x, y);
        }
        return flat;
      })
      .filter((ring) => ring.length >= 6);
    return { name: feature.properties.name, rings };
  }),
);

// -------------------------------------------------------------------- blog

const posts = readdirSync(join(SRC, "content", "blog"))
  .filter((f) => f.endsWith(".md") && !f.startsWith("_"))
  .map((file) => {
    const { data, body } = parseFrontMatter(read(SRC, "content", "blog", file));
    if (!data.title || !data.pubDate) throw new Error(`${file}: front matter needs "title" and "pubDate"`);
    return {
      id: file.replace(/\.md$/, ""),
      title: data.title,
      description: data.description ?? "",
      date: data.pubDate,
      link: data.link,
      categories: Array.isArray(data.categories) ? data.categories : [],
      minutes: readingMinutes(body),
      html: renderMarkdown(body),
    };
  })
  .sort((a, b) => b.date.localeCompare(a.date));

// ---------------------------------------------------------------- terminal
// Everything the terminal can print. It ships as JSON so the shell never
// needs a network request.

// The hidden statistics command: where to check the passkey and where the
// dashboard is. Same origin when the site runs behind server/server.mjs.
const statsEndpoint = SITE.analytics?.endpoint ?? "";
const statsAccess = !statsEndpoint || !SITE.statsCommand
  ? null
  : statsEndpoint.startsWith("/")
    ? { command: SITE.statsCommand.toLowerCase(), api: `${BASE}/api/stats`, page: `${BASE}/stats` }
    : { command: SITE.statsCommand.toLowerCase(), api: null, page: `${new URL(statsEndpoint).origin}/stats` };

const termData = {
  base: BASE,
  stats: statsAccess,
  name: SITE.author.fullName,
  title: SITE.author.jobTitle,
  location: SITE.location.label,
  email: SITE.links.email,
  links: { github: SITE.links.github, linkedin: SITE.links.linkedin, medium: SITE.links.medium },
  resume: Object.fromEntries(SITE.resume.map((r) => [r.lang, SITE.url + BASE + r.file])),
  now: SITE.now.text,
  about: C.intro.paragraphs,
  stack: C.stack.map((g) => [g.group, g.items.join(", ")]),
  projects: C.projects.map((p) => ({ name: p.name, year: p.year, text: p.description, stack: p.stack.join(" · "), repo: p.repo })),
  talks: C.talks.map((t) => ({ slug: t.slug, event: t.event, city: t.location, date: t.date, title: t.title, slides: t.slideCount })),
  certs: C.certifications.map((c) => ({ short: c.short, name: c.name, issuer: c.issuer, status: c.status })),
  awards: C.awards.map((a) => [a.period, a.title]),
  jobs: C.experience.map((j) => [`${j.start} - ${j.end}`, j.title, j.company]),
  languages: C.languages.map((l) => [l.name, l.level]),
  countries: SITE.visitedCountries,
  posts: posts.map((p) => ({ id: p.id, title: p.title })),
  moments: C.moments.length,
  themes: THEMES.map((t) => t.id),
  pages: { home: "/", projects: "/projects/", talks: "/talks/", certs: "/certifications/", certifications: "/certifications/", moments: "/moments/", blog: "/blog/", travel: "/travel/", contact: "/#contact" },
};

// ------------------------------------------------------------------- pages

const pages = [
  { path: "/", home: true, title: SITE.title, description: SITE.description, body: homePage(), jsonLd: homeJsonLd() },
  { path: "/projects/", title: "Projects", description: "Kubernetes operators, container networking, provisioning tools and security projects by Mohamed Ali Mellah.", body: P.projectsPage() },
  { path: "/talks/", title: "Talks", description: "Conference talks by Mohamed Ali Mellah, with slides: ContainerDays Hamburg and Cloud Identity Summit 2026.", body: P.talksPage() },
  ...C.talks.map((t) => ({ path: `/talks/${t.slug}/`, title: t.shortTitle, description: t.description, body: P.talkPage(t), image: `${t.slidesDir}/01-1600.webp` })),
  { path: "/certifications/", title: "Certifications", description: "CKA, CKAD, RHCSA, eJPT, AWS and Cisco certifications held by Mohamed Ali Mellah.", body: P.certificationsPage() },
  { path: "/moments/", title: "Moments", description: "Photos from talks, competitions and university.", body: P.momentsPage() },
  { path: "/blog/", title: "Blog", description: "Notes on Kubernetes security, DevSecOps and platform engineering.", body: P.blogPage(posts) },
  ...posts.map((post) => ({ path: `/blog/${post.id}/`, title: post.title, description: post.description, body: P.postPage(post) })),
  { path: "/travel/", title: "Travel", description: `${SITE.visitedCountries.length} countries visited so far. Drag the globe to spin it.`, body: P.travelPage(u(`${assetDir}/world.json`)) },
  { path: "/privacy/", title: "Privacy", description: "What this site records about a visit: no cookies, anonymous statistics.", body: P.privacyPage() },
];

// ------------------------------------------------------------------- write

rmSync(DIST, { recursive: true, force: true });
cpSync(join(ROOT, "public"), DIST, { recursive: true });

// The statistics dashboard (/stats). The Node server serves it from
// server/dashboard itself; on Netlify it is a static page that talks to the
// /api/stats function. Only built when statistics go to this same site.
if (statsAccess?.api) cpSync(join(ROOT, "server", "dashboard"), join(DIST, "stats"), { recursive: true });

write(`${assetDir}/site.css`, css);
write(`${assetDir}/world.json`, worldData);
for (const f of clientFiles) write(`${assetDir}/js/${f}`, read(SRC, "client", f));

for (const page of pages) {
  write(join(page.path, "index.html"), String(layout({ ...page, assets, termData })));
}
write(
  "404.html",
  String(layout({ path: "/404.html", title: "Not found", description: "This page does not exist.", body: P.notFoundPage(), assets, termData })),
);

// /qr: the address behind a printed QR code. It reports the scan and always
// goes on to the homepage. Kept tiny so it loads instantly; the meta refresh
// covers browsers without JavaScript.
write(
  "qr/index.html",
  `<!doctype html>
<html lang="en" data-base="${escapeHtml(BASE)}" data-analytics="${escapeHtml(analyticsUrl())}">
<head>
<meta charset="utf-8">
<meta name="robots" content="noindex">
<meta http-equiv="Content-Security-Policy" content="${escapeHtml(CSP)}">
<meta http-equiv="refresh" content="2; url=${escapeHtml(BASE)}/">
<title>${escapeHtml(SITE.title)}</title>
<script src="${escapeHtml(u(`${assetDir}/js/qr.js`))}"></script>
</head>
<body>
<p><a href="${escapeHtml(BASE)}/">Continue to ${escapeHtml(SITE.title)}</a></p>
</body>
</html>
`,
);

const abs = (path) => SITE.url + BASE + path;

write(
  "sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    pages.map((p) => `  <url><loc>${escapeHtml(abs(p.path))}</loc></url>`).join("\n") +
    `\n</urlset>\n`,
);

write("robots.txt", `User-agent: *\nAllow: /\nDisallow: /stats\n\nSitemap: ${abs("/sitemap.xml")}\n`);

write(
  "rss.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<rss version="2.0"><channel>\n` +
    `<title>${escapeHtml(SITE.title)}</title>\n<link>${escapeHtml(abs("/blog/"))}</link>\n` +
    `<description>${escapeHtml("Notes on Kubernetes security, DevSecOps and platform engineering.")}</description>\n` +
    posts
      .map(
        (p) =>
          `<item><title>${escapeHtml(p.title)}</title><link>${escapeHtml(abs(`/blog/${p.id}/`))}</link>` +
          `<guid>${escapeHtml(abs(`/blog/${p.id}/`))}</guid><pubDate>${new Date(`${p.date}T12:00:00Z`).toUTCString()}</pubDate>` +
          `<description>${escapeHtml(p.description)}</description></item>`,
      )
      .join("\n") +
    `\n</channel></rss>\n`,
);

// Response headers for Netlify and Cloudflare Pages (both read dist/_headers).
// frame-ancestors only works as a header, so it is added here.
write(
  "_headers",
  [
    "/*",
    `  Content-Security-Policy: ${CSP}; frame-ancestors 'none'; upgrade-insecure-requests`,
    "  X-Content-Type-Options: nosniff",
    "  X-Frame-Options: DENY",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
    "  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload",
    "  Cross-Origin-Opener-Policy: same-origin",
    "",
    `${BASE}/assets/*`,
    "  Cache-Control: public, max-age=31536000, immutable",
    "",
    `${BASE}/fonts/*`,
    "  Cache-Control: public, max-age=31536000, immutable",
    "",
  ].join("\n"),
);

console.log(`Built ${pages.length + 1} pages into dist/ (assets ${version}${BASE ? `, base ${BASE}` : ""})`);
